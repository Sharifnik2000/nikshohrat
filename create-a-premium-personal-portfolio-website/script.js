document.addEventListener("keydown", (event) => {
  if (isContactOpen()) {
    if (event.key === "Tab") trapFocus(event, contactModal);
    if (event.key === "Escape") closeContactModal();
    return;
  }

  if (isLightboxOpen()) {
    if (event.key === "Tab") trapFocus(event, lightbox);
    if (event.key === "Escape") closeLightbox();
    if (event.key === "ArrowLeft") {
      event.preventDefault();
      if (lightboxZoomIndex > 0) {
        moveLightboxPan(48, 0);
      } else {
        setLightboxImage(currentImageIndex - 1);
      }
    }
    if (event.key === "ArrowRight") {
      event.preventDefault();
      if (lightboxZoomIndex > 0) {
        moveLightboxPan(-48, 0);
      } else {
        setLightboxImage(currentImageIndex + 1);
      }
    }
    if (event.key === "ArrowUp" && lightboxZoomIndex > 0) {
      event.preventDefault();
      moveLightboxPan(0, 48);
    }
    if (event.key === "ArrowDown" && lightboxZoomIndex > 0) {
      event.preventDefault();
      moveLightboxPan(0, -48);
    }
    if (event.key === "+" || event.key === "=") {
      event.preventDefault();
      setLightboxZoom(lightboxZoomIndex + 1);
    }
    if (event.key === "-") {
      event.preventDefault();
      setLightboxZoom(lightboxZoomIndex - 1);
    }
    return;
  }

  if (modal.classList.contains("is-open")) {
    if (event.key === "Tab") trapFocus(event, modal);
    if (event.key === "Escape") closeModal();
  }
});

